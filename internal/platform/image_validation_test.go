func TestMinIOImagePayloadValidation(t *testing.T) {
	endpoint := os.Getenv("GOSTREAM_TEST_MINIO_ENDPOINT")
	if endpoint == "" {
		t.Skip("set GOSTREAM_TEST_MINIO_ENDPOINT to a disposable MinIO server")
	}
	var nonce [8]byte
	if _, err := rand.Read(nonce[:]); err != nil {
		t.Fatal(err)
	}
	bucket := "gostream-images-" + hex.EncodeToString(nonce[:])
	store, err := NewMinIOMediaStore(context.Background(), endpoint, os.Getenv("GOSTREAM_TEST_MINIO_ACCESS_KEY"), os.Getenv("GOSTREAM_TEST_MINIO_SECRET_KEY"), bucket, false)
	if err != nil {
		t.Fatal(err)
	}
	t.Cleanup(func() {
		ctx, cancel := context.WithTimeout(context.Background(), 30*time.Second)
		defer cancel()
		for _, prefix := range []string{"media/", "chunks/"} {
			if err := store.removePrefix(ctx, prefix); err != nil {
				t.Errorf("remove %s: %v", prefix, err)
			}
		}
		if err := store.client.RemoveBucket(ctx, bucket); err != nil {
			t.Errorf("remove bucket: %v", err)
		}
	})
	s, h, db := testServer(t)
	s.UseObjectMedia(store)
	testImageUploadsRejectTruncatedPayloads(t, h, db)
}

func testImageUploadsRejectTruncatedPayloads(t *testing.T, h http.Handler, db *gorm.DB) {
	t.Helper()
	ownerID, ownerToken := registerTestUser(t, h, "image_owner")
	_, otherToken := registerTestUser(t, h, "image_other")
	img := image.NewRGBA(image.Rect(0, 0, 16, 16))
	img.Set(0, 0, color.RGBA{R: 255, A: 255})
	var pngData, jpegData bytes.Buffer
	if err := png.Encode(&pngData, img); err != nil {
		t.Fatal(err)
	}
	if err := jpeg.Encode(&jpegData, img, nil); err != nil {
		t.Fatal(err)
	}
	// A 16x16 lossless WebP generated by FFmpeg. Keep the fixture small so
	// both direct and resumable paths exercise the same payload.
	webpData, err := base64.StdEncoding.DecodeString("UklGRhwAAABXRUJQVlA4TA8AAAAvD8ADAAcQ9Y/+ByKi/wEA")
	if err != nil {
		t.Fatal(err)
	}
	fixtures := []struct {
		name string
		data []byte
	}{
		{"image.png", pngData.Bytes()},
		{"image.jpg", jpegData.Bytes()},
		{"image.jpeg", jpegData.Bytes()},
		{"image.webp", webpData},
	}
	var webpURL string
	for _, fixture := range fixtures {
		t.Run(fixture.name, func(t *testing.T) {
			good := uploadTestMedia(t, h, ownerToken, fixture.name, fixture.data)
			if good.Code != http.StatusCreated {
				t.Fatalf("direct valid image: %d %s", good.Code, good.Body.String())
			}
			var asset struct {
				URL string `json:"url"`
			}
			if err := json.Unmarshal(good.Body.Bytes(), &asset); err != nil || asset.URL == "" {
				t.Fatalf("direct asset: %v %s", err, good.Body.String())
			}
			if fixture.name == "image.webp" {
				webpURL = asset.URL
			}
			truncated := fixture.data[:len(fixture.data)-2]
			if mediaKind("."+fixture.name[6:], truncated) != "image" {
				t.Fatal("truncated fixture does not preserve an accepted image signature")
			}
			if bad := uploadTestMedia(t, h, ownerToken, fixture.name, truncated); bad.Code != http.StatusBadRequest {
				t.Fatalf("direct truncated image: %d %s", bad.Code, bad.Body.String())
			}
			completeSession := func(data []byte, want int) {
				t.Helper()
				create := request(t, h, http.MethodPost, "/api/uploads/sessions", ownerToken, map[string]any{
					"filename": fixture.name, "size": len(data),
				})
				if create.Code != http.StatusCreated {
					t.Fatalf("create resumable session: %d %s", create.Code, create.Body.String())
				}
				var session struct {
					ID string `json:"id"`
				}
				if err := json.Unmarshal(create.Body.Bytes(), &session); err != nil || session.ID == "" {
					t.Fatalf("session: %v %s", err, create.Body.String())
				}
				if chunk := putTestChunk(h, ownerToken, session.ID, 0, data); chunk.Code != http.StatusOK {
					t.Fatalf("chunk: %d %s", chunk.Code, chunk.Body.String())
				}
				if result := request(t, h, http.MethodPost, "/api/uploads/sessions/"+session.ID+"/complete", ownerToken, nil); result.Code != want {
					t.Fatalf("complete image: %d, want %d: %s", result.Code, want, result.Body.String())
				}
				if want != http.StatusOK {
					if status := request(t, h, http.MethodGet, "/api/uploads/sessions/"+session.ID, ownerToken, nil); status.Code != http.StatusOK || !bytes.Contains(status.Body.Bytes(), []byte(`"status":"open"`)) {
						t.Fatalf("failed session was not released: %d %s", status.Code, status.Body.String())
					}
				}
			}
			completeSession(fixture.data, http.StatusOK)
			completeSession(truncated, http.StatusBadRequest)
		})
	}
	var count int64
	if err := db.Model(&MediaAsset{}).Where("owner_id = ?", ownerID).Count(&count).Error; err != nil || count != int64(2*len(fixtures)) {
		t.Fatalf("rejected images registered: count=%d err=%v", count, err)
	}
	if r := request(t, h, http.MethodPatch, "/api/users/me", otherToken, map[string]string{"avatar_url": webpURL}); r.Code != http.StatusBadRequest {
		t.Fatalf("foreign WebP avatar accepted: %d %s", r.Code, r.Body.String())
	}
	if r := request(t, h, http.MethodPatch, "/api/users/me", ownerToken, map[string]string{"avatar_url": webpURL}); r.Code != http.StatusOK {
		t.Fatalf("owner WebP avatar rejected: %d %s", r.Code, r.Body.String())
	}
}

func TestImagePixelBudgetRejectsLargeHeader(t *testing.T) {
	img := image.NewRGBA(image.Rect(0, 0, 16, 16))
	var encoded bytes.Buffer
	if err := png.Encode(&encoded, img); err != nil {
		t.Fatal(err)
	}
	data := bytes.Clone(encoded.Bytes())
	// Keep a valid PNG header and CRC, but advertise 20 million pixels.
	// DecodeConfig must accept the header so this checks the pre-decode bound.
	binary.BigEndian.PutUint32(data[16:20], 5000)
	binary.BigEndian.PutUint32(data[20:24], 4000)
	binary.BigEndian.PutUint32(data[29:33], crc32.ChecksumIEEE(data[12:29]))
	config, format, err := image.DecodeConfig(bytes.NewReader(data))
	if err != nil || format != "png" || config.Width != 5000 || config.Height != 4000 {
		t.Fatalf("large PNG fixture header: %+v %q %v", config, format, err)
	}
	server, h, db := testServer(t)
	_, token := registerTestUser(t, h, "large_image_owner")
	if r := uploadTestMedia(t, h, token, "large.png", data); r.Code != http.StatusBadRequest {
		t.Fatalf("large image accepted: %d %s", r.Code, r.Body.String())
	}
	var count int64
	if err := db.Model(&MediaAsset{}).Count(&count).Error; err != nil || count != 0 {
		t.Fatalf("large image registered: %d %v", count, err)
	}
	entries, err := os.ReadDir(server.MediaDir)
	if err != nil || len(entries) != 0 {
		t.Fatalf("large image left local media: %d %v", len(entries), err)
	}
}
